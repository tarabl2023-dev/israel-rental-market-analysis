# 05_export_market_data.R
# Export current asking rents (listings on the market today) for the calculator.
#
# CBS Table 4.9 averages every lease signed in a quarter, including renewals of
# long-running contracts, so it runs well below what a newcomer pays. Realta
# (realta.co.il) aggregates live listings from Yad2, Madlan, OnMap, Homeless,
# Komo and Facebook and publishes the median asking rent by town, room count
# and neighbourhood. This script turns that snapshot into the calculator's
# rent level, with CBS kept as the official reference.
#
# Inputs : data/raw/realta_city_rooms_2026-10-26.csv          (60 towns, by English name)
#          data/raw/realta_town_rooms_2026-10-26.csv          (34 smaller towns, by Realta slug)
#          data/raw/realta_neighbourhood_rents_2026-10-26.csv (mean asking rent per neighbourhood)
#          data/raw/places.csv                                (district and CBS cost sub-district per town)
#          data/raw/beach_neighbourhoods.csv                  (seaside neighbourhoods, local knowledge)
# Output : docs/market-data.js  (loaded by docs/index.html)

library(tidyverse)
library(jsonlite)

snapshot_date <- "2026-10-26"

places <- read_csv("data/raw/places.csv", show_col_types = FALSE)

room_cols <- c("r1", "r1n", "r2", "r2n", "r3", "r3n", "r4", "r4n", "r5", "r5n", "r6", "r6n")
big <- read_csv("data/raw/realta_city_rooms_2026-10-26.csv", show_col_types = FALSE) |>
  rename(name = city) |>
  left_join(places, by = "name")
small <- read_csv("data/raw/realta_town_rooms_2026-10-26.csv", show_col_types = FALSE) |>
  rename(realta_slug = slug) |>
  left_join(places, by = "realta_slug")

towns <- bind_rows(big, small)
stopifnot(!anyNA(towns$name), !anyNA(towns$realta_slug), !anyDuplicated(towns$name))

hoods <- read_csv("data/raw/realta_neighbourhood_rents_2026-10-26.csv", show_col_types = FALSE) |>
  left_join(select(towns, city_slug = realta_slug, city = name, city_mean = mean), by = "city_slug") |>
  left_join(read_csv("data/raw/beach_neighbourhoods.csv", show_col_types = FALSE,
                     col_types = cols(.default = "c")) |> mutate(beach = TRUE),
            by = c("city_slug", "slug")) |>
  mutate(
    beach = coalesce(beach, FALSE),
    # English name from Realta's transliterated slug, e.g. "old-north-southwest-part"
    en = slug |> str_replace_all(";-?", "; ") |> str_replace_all("-", " ") |> str_squish() |> str_to_title(),
    # Price relative to the town: a neighbourhood with only a handful of ads is
    # pulled towards the town average (shrinkage with a prior worth 3 ads)
    raw_factor = mean_rent / city_mean,
    factor = 1 + (raw_factor - 1) * listings / (listings + 3),
    factor = pmin(pmax(factor, 0.5), 3)
  )
stopifnot(!anyNA(hoods$city))
missing_beach <- anti_join(read_csv("data/raw/beach_neighbourhoods.csv", show_col_types = FALSE),
                           hoods, by = c("city_slug", "slug"))
stopifnot(nrow(missing_beach) == 0)

message("Rehavia check: ", with(filter(hoods, slug == "rehavia"),
  sprintf("factor %.3f, 4 rooms ~ NIS %.0f", factor, factor * towns$r4[towns$name == "Jerusalem"])))

payload <- list(
  date = snapshot_date,
  source = "Realta (realta.co.il) rent-price pages: median asking rent of live listings, aggregated from Yad2, Madlan, OnMap, Homeless, Komo and Facebook",
  towns = map(set_names(towns$name), \(n) {
    t <- filter(towns, name == n)
    list(
      slug = t$realta_slug,
      he = t$name_he,
      district = t$district,
      region = t$cost_region,
      listings = t$listings,
      median = t$median,
      mean = t$mean,
      # [median asking rent, number of listings] for 1-6 rooms (6 = 6 or more)
      rooms = map(1:6, \(k) c(t[[paste0("r", k)]], t[[paste0("r", k, "n")]]))
    )
  }),
  hoods = map(set_names(unique(hoods$city)), \(c) {
    hoods |>
      filter(city == c) |>
      arrange(en) |>
      transmute(s = slug, he = name_he, en, avg = mean_rent, n = listings, f = round(factor, 3),
                beach, yad2 = yad2_hood)
  })
)

writeLines(
  enc2utf8(c("// Generated by R/05_export_market_data.R - do not edit by hand",
    paste0("window.MARKET_DATA = ", toJSON(payload, auto_unbox = TRUE, na = "null",
                                           digits = NA, dataframe = "rows"), ";"))),
  "docs/market-data.js",
  useBytes = TRUE
)

message(sprintf("Market data: %d towns, %d neighbourhoods (%d by the beach), snapshot %s",
                nrow(towns), nrow(hoods), sum(hoods$beach), snapshot_date))
